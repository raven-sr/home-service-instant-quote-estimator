
import { useEffect, useState } from "react";
import api from "../../services/api";

export default function AdminQuotationsPage() {
  const [quotations, setQuotations] = useState([]);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState("");

  const fetchQuotations = async () => {
    try {
      setLoading(true);
      setError("");

      const response = await api.get("/admin/quotations");

      setQuotations(response.data.quotations || []);
    } catch (err) {
      setError(
        err.response?.data?.message ||
          "Failed to load quotations."
      );
    } finally {
      setLoading(false);
    }
  };

  useEffect(() => {
    fetchQuotations();
  }, []);

  const getStatusBadge = (status) => {
    const colors = {
      draft: "secondary",
      sent: "primary",
      accepted: "success",
      rejected: "danger",
    };

    return (
      <span
        className={`badge bg-${colors[status] || "secondary"} text-capitalize`}
      >
        {status || "Unknown"}
      </span>
    );
  };

  return (
    <div className="container-fluid py-4">
      <div className="d-flex justify-content-between align-items-center mb-4">
        <div>
          <h2 className="fw-bold">Quotations Management</h2>
          <p className="text-muted mb-0">
            Monitor quotations generated by contractors.
          </p>
        </div>

        <button
          className="btn btn-outline-primary"
          onClick={fetchQuotations}
        >
          Refresh
        </button>
      </div>

      <div className="card border-0 shadow-sm mb-4">
        <div className="card-body">
          <h6 className="text-muted">Total Quotations</h6>
          <h2 className="fw-bold mb-0">
            {loading ? "..." : quotations.length}
          </h2>
        </div>
      </div>

      {error && (
        <div className="alert alert-danger">{error}</div>
      )}

      {loading ? (
        <div className="text-center py-5">
          <div className="spinner-border text-primary" />
          <p className="mt-2">Loading quotations...</p>
        </div>
      ) : (
        <div className="table-responsive bg-white rounded shadow-sm">
          <table className="table table-hover align-middle mb-0">
            <thead className="table-light">
              <tr>
                <th>Quotation ID</th>
                <th>Homeowner</th>
                <th>Contractor</th>
                <th>Service</th>
                <th>Total Amount</th>
                <th>Status</th>
                <th>Created Date</th>
              </tr>
            </thead>

            <tbody>
              {quotations.length > 0 ? (
                quotations.map((quotation) => (
                  <tr key={quotation._id}>
                    <td>
                      <small className="text-muted">
                        {quotation._id.slice(-8).toUpperCase()}
                      </small>
                    </td>

                    <td>
                      {quotation.homeowner?.name || "—"}
                    </td>

                    <td>
                      {quotation.contractor?.name || "—"}
                    </td>

                    <td className="text-capitalize">
                      {quotation.serviceType || "—"}
                    </td>

                    <td className="fw-semibold">
                      {quotation.currency || "INR"}{" "}
                      {Number(quotation.totalCost || 0).toLocaleString(
                        "en-IN"
                      )}
                    </td>

                    <td>{getStatusBadge(quotation.status)}</td>

                    <td>
                      {quotation.createdAt
                        ? new Date(
                            quotation.createdAt
                          ).toLocaleDateString()
                        : "—"}
                    </td>
                  </tr>
                ))
              ) : (
                <tr>
                  <td colSpan="7" className="text-center py-4">
                    No quotations found.
                  </td>
                </tr>
              )}
            </tbody>
          </table>
        </div>
      )}
    </div>
  );
}
